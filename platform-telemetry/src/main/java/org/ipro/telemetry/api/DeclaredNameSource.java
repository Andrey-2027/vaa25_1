package org.ipro.telemetry.api;

/**
 * Источник объявленного имени сущности — для снимков аудита.
 *
 * <p>Существует ради направления зависимостей. Снимок изменений ({@code EntitySnapshot})
 * раньше звал статику {@code org.ipro.fetch.instance.InstanceNameBridge.declaredName}, то
 * есть подсистема наблюдения зависела от подсистемы выборки: чтобы залогировать изменение,
 * телеметрии нужен был класс из верхнего слоя. Теперь наблюдение знает только этот
 * интерфейс, а реализацию (мост объявленных имён fetch-плана) ставит
 * {@code org.ipro.telemetry.core.DeclaredNameBridge}.</p>
 *
 * <p>Контракт намеренно возвращает {@code null}, а не пустую строку: потребители различают
 * «у типа есть объявление» и «объявления нет» — во втором случае имя выводится прежним
 * рефлексивным способом ({@code getDisplayName}), чтобы аудит не менял представление
 * немигрированных сущностей.</p>
 */
@FunctionalInterface
public interface DeclaredNameSource {

    /** Объявленное имя значения или {@code null}, если у типа нет объявления. */
    String declaredName(Object entity);
}
