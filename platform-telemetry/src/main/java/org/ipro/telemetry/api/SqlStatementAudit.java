package org.ipro.telemetry.api;

/**
 * Наблюдатель SQL-текста: единственная точка расширения для аудиторов стейтментов.
 *
 * <p>Существует ради направления зависимостей. До D2 → D3 (пара `telemetry` + `rls`)
 * инспектор стейтментов телеметрии вызывал канарейку RLS напрямую
 * ({@code org.ipro.rls.RlsStatementGuard}), из-за чего слой наблюдения не собирался без
 * слоя принуждения: конфигурация телеметрии не поднялась бы в развёртывании без RLS.
 * Теперь наблюдение знает только этот интерфейс, а кто именно наблюдает — решает тот, кто
 * устанавливает реализацию (RLS ставит свою канарейку через
 * {@code org.ipro.telemetry.core.SqlStatementAuditBridge}).</p>
 *
 * <p>Инспектор вызывает наблюдателей <b>до</b> своих ранних выходов по
 * {@code TelemetryGuard}, поэтому реализация работает независимо от того, включена ли
 * телеметрия и что она пишет: это свойство было и до выворота, и его надо сохранить.</p>
 */
@FunctionalInterface
public interface SqlStatementAudit {

    /** Вызывается на каждый SQL-текст, подготовленный Hibernate. */
    void audit(String sql);
}
