package org.ipro.fetch.plan;

/**
 * Сценарий загрузки сущности — часть ключа FetchPlan (C3, см. ADR-0006).
 *
 * <p>Один и тот же класс в разных сценариях требует разного набора связей, и планы не
 * смешиваются: то, что нужно для рендера строки списка, не обязано грузиться в форму
 * выбора, и наоборот.</p>
 */
public enum FetchScenario {

    /** Строки Формы Списка: то, что читает рендер колонок. */
    LIST,

    /** Форма Элемента: поля формы и имя сущности. */
    DETAIL,

    /** Форма Выбора / автокомплит: колонки выбора, имя цели и объявленные зависимости выбора. */
    LOOKUP,

    /** Строка табличной части (owned section row). */
    ROW
}
