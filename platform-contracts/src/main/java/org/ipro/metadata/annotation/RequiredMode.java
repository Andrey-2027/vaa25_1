package org.ipro.metadata.annotation;

/**
 * Трёхзначный режим обязательности поля (C4.2, ADR-0007 §6).
 *
 * <p>Прежний {@code boolean required} не различал «явно необязательно» и «не задано».
 * Из-за этого вывод обязательности из контракта записи (Bean Validation, JPA) был
 * невозможен без ломающего изменения всех полей, где {@code required} просто не писали:
 * отсутствие атрибута неотличимо от {@code false}.</p>
 *
 * <ul>
 * <li>{@link #AUTO} — вывести из контракта записи ({@code @NotNull}/{@code @NotBlank}/
 * {@code @NotEmpty} в Bean Validation, затем {@code nullable = false} в JPA-маппинге);
 * если контракт записи значения не требует — поле необязательно;</li>
 * <li>{@link #REQUIRED} — явное требование UI; при server-optional это осознанное
 * ограничение формы, а не тихий рассинхрон (диагностика warning);</li>
 * <li>{@link #OPTIONAL} — явный отказ от требования; при server-required это ошибка
 * конфигурации, потому что UI позволил бы ввести данные, которые сервер отклонит.</li>
 * </ul>
 */
public enum RequiredMode {

    /** Вывести обязательность из контракта записи, а не из объявления. */
    AUTO,

    /** Поле обязано быть заполнено в UI (как минимум не слабее server-контракта). */
    REQUIRED,

    /** Поле необязательно в UI (несовместимо с server-required). */
    OPTIONAL
}
