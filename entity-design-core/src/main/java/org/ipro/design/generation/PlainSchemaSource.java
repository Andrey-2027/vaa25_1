package org.ipro.design.generation;

import org.ipro.design.CheckedStructure;

final class PlainSchemaSource {
    private PlainSchemaSource() {}

    static GenerationFile file(CheckedStructure checked) {
        var root = checked.root();
        var ddl = new StringBuilder("CREATE TABLE ").append(root.tableName()).append(" (\n")
            .append("    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,\n")
            .append("    version BIGINT,\n")
            .append("    created_at TIMESTAMP(6),\n")
            .append("    modified_at TIMESTAMP(6),\n")
            .append("    created_by VARCHAR(255),\n")
            .append("    modified_by VARCHAR(255)");
        for (var field : checked.fields()) {
            ddl.append(",\n    ").append(field.columnName()).append(' ').append(sqlType(field));
            if (field.serverRequired()) ddl.append(" NOT NULL");
        }
        String content = ddl.append("\n);\n").toString();
        return new GenerationFile(GenerationFile.Operation.CREATE, "schema/" + root.className() + ".sql",
            content, GenerationHash.sha256(content));
    }

    private static String sqlType(CheckedStructure.Field field) {
        return switch (field.type()) {
            case STRING -> "VARCHAR(" + field.length() + ")";
            case INTEGER -> "INTEGER";
            case LONG -> "BIGINT";
            case DECIMAL -> "NUMERIC(" + field.precision() + "," + field.scale() + ")";
            case BOOLEAN -> "BOOLEAN";
            case DATE -> "DATE";
            case DATETIME -> "TIMESTAMP(6)";
            case REFERENCE -> throw new IllegalArgumentException("PLAIN supports scalar columns only");
        };
    }
}
