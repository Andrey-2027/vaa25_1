package org.ipro.crud;

/**
 * Экземпляр, который платформа <b>интернирует</b>: строку нельзя создать «свободно», её
 * находит или создаёт одна операция по натуральному ключу, а сам ключ закреплён уникальным
 * индексом БД.
 *
 * <p>Это не третий архетип рядом со справочником и документом, а признак двух независимых
 * свойств, уже поддержанных платформой по отдельности:</p>
 * <ul>
 * <li><b>профиль записи</b> выражается capability типа
 * ({@code descriptor.capabilities().writes()}): у интернированного типа generic
 * {@code UPDATE}/{@code DELETE} не выдаются, а у части типов не выдан и {@code CREATE} —
 * тогда создание принадлежит канонизации ({@code findOrCreate}), а не общему пути;</li>
 * <li><b>идентичность</b> — то, что описывает этот интерфейс: ключ, по которому экземпляры
 * дедуплицируются, и который обязан иметь уникальное ограничение в схеме. Именно поэтому
 * маркер поведенческий, а не {@code @MappedSuperclass}: общих колонок у таких типов нет
 * (у одного набор значений атрибутов, у другого тип+значение словаря, у следующего —
 * заказ+ДСЕ+пара цехов), а общность здесь только в поведении.</li>
 * </ul>
 *
 * <p>Не путать с {@link StandardCatalogEntity}: у справочника код тоже выглядит натуральным
 * ключом, но глобальная uniqueness там <b>намеренно не задаётся</b> — справочник ведёт
 * пользователь, строки живут сами по себе. Интернированный экземпляр — наоборот:
 * дедупликация обязана быть гарантирована схемой, иначе гонка двух создателей даст дубль.
 * Тот же признак отличает эти типы от DDD value object: у них есть идентичность и на них
 * ссылаются внешние ключи.</p>
 *
 * <p>«Неизменяемость» здесь означает «нет пользовательского редактирования содержимого и
 * идентичности», а не «нет UPDATE вообще»: производный кэш отображения (например
 * {@code SklNomOpa.displayName}) может пересобираться той же транзакцией, что и
 * переименование источника.</p>
 */
public interface InternedEntity {

    /**
     * Каноническая строка идентичности: стабильна для равных по содержимому экземпляров и
     * однозначно соответствует уникальному индексу типа. Используется диагностикой
     * интернирования (какой именно ключ не разрешился при гонке) и проверкой контракта типа.
     */
    String interningKey();
}
