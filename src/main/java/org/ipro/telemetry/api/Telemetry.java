package org.ipro.telemetry.api;

import java.util.Map;

/**
 * Фасад подсистемы телеметрии для явных вызовов из UI и фоновых задач.
 * <p>
 * Направление: UI → telemetry (без обратной зависимости телеметрии от UI).
 * Операции сервисного слоя перехватываются AOP-аспектом автоматически;
 * явные вызовы нужны для контекста форм, фоновых задач и именованных операций.
 */
public interface Telemetry {

    /**
     * Начать операцию. Если на потоке уже есть активная операция,
     * новый вызов НЕ создаёт вложенную операцию (правило «первый вход
     * побеждает») — вернётся no-op-скоуп, привязанный к активной.
     */
    OperationScope beginOperation(String name);

    /**
     * Начать операцию с дополнительным контекстом (класс+id сущности,
     * форма, вариант), который кладётся в MDC на время операции.
     */
    OperationScope beginOperation(String name, Map<String, String> context);

    /** Положить ключи в MDC на время текущей операции. */
    void context(Map<String, String> values);
}
