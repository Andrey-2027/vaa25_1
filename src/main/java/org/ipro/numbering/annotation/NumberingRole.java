package org.ipro.numbering.annotation;

/**
 * Семантическая роль нумеруемого поля. Роль позволяет конкретной сущности менять
 * политику унаследованного стандартного поля, не затеняя его новым Java-полем.
 */
public enum NumberingRole {
    /** Произвольное прикладное нумеруемое поле; настраивается непосредственно через @Numbered. */
    CUSTOM,

    /** Стандартное поле code сущности-справочника. */
    CATALOG_CODE,

    /** Стандартное поле number сущности-документа. */
    DOCUMENT_NUMBER
}
