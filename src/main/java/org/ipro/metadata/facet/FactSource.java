package org.ipro.metadata.facet;

/**
 * Источник значения грани. На срезе 1 Entity Explorer показывает только «код»;
 * {@link #OVERRIDE} появится со store-слоем роли 3 (хранилище переопределений),
 * когда резолюция начнёт подставлять значения поверх кодовых дефолтов.
 */
public enum FactSource {

    /** Значение из кода (аннотация/конфиг регистрации). */
    CODE,

    /** Значение из хранилища переопределений администратора (роль 3, будущий слой). */
    OVERRIDE
}
