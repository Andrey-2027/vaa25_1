package org.ipro.reportstudio.dom;

/**
 * Предвычисленное значение для параметра с источником COMPUTED (Фаза 3).
 */
public enum ReportComputedValue {

    /** Не используется (любой другой источник). */
    NONE,
    /** Текущий момент времени; фиксируется при построении контекста запуска. */
    NOW,
    /** Текущий пользователь (username). */
    CURRENT_USER,
    /** Организация из RLS-контекста текущего пользователя. */
    RLS_ORG
}