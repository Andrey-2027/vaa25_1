package org.ip.views.admin;

import java.util.Optional;

/**
 * Вкладка карточки сущности: аспект или природная группа разделов (E3.2.1). Порядок объявления —
 * порядок вкладок на экране; разделы ссылаются на вкладку в {@link CardSection}, а не наоборот.
 *
 * <p>Вкладка без непустых разделов не рисуется: заголовок без строк читался бы как «в разделе нет
 * данных», хотя раздела в композиции карточки нет вовсе.</p>
 *
 * <p>Уровень сущностей в Explorer — хост: там одна карточка выбранного типа (E3.2.2 §9.2), и
 * этот словарь его не заменяет: здесь уровень аспектов <b>внутри</b> карточки, и третьего
 * уровня не заводится.</p>
 */
enum CardTab {

    /** Обзор типа и стартовый скан метаданных. */
    OVERVIEW("overview", "Обзор"),
    /** Поля и колонки: форма, грид, списки, выбор и табличные части. */
    FIELDS("fields", "Поля и колонки"),
    /** Формы, их варианты, контекст-фильтры, наборы выбора и действия. */
    FORMS("forms", "Формы и действия"),
    /** Сценарии чтения и их пути. */
    READING("reading", "Чтение"),
    /** Измерения RLS и правила значений. */
    ACCESS("access", "Доступ"),
    /** Цели выбора полей и обратные ссылки. */
    LINKS("links", "Связи"),
    /** Нумерация и lifecycle. */
    BEHAVIOR("behavior", "Поведение");

    private final String id;
    private final String title;

    CardTab(String id, String title) {
        this.id = id;
        this.title = title;
    }

    /** Идентификатор вкладки для якоря адреса: латиница, строчные, без пробелов. */
    String id() {
        return id;
    }

    /**
     * Вкладка по id адреса; пусто — такого якоря словарь не знает (см. {@link CardAnchor}).
     * Поиск идёт по тому же id, что попадает в адрес: второго имени у вкладки нет.
     */
    static Optional<CardTab> byId(String id) {
        for (CardTab tab : values()) {
            if (tab.id.equals(id)) {
                return Optional.of(tab);
            }
        }
        return Optional.empty();
    }

    /** Заголовок вкладки — текст для человека. */
    String title() {
        return title;
    }
}
