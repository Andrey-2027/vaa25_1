package org.ip.application.catalog;

/**
 * Владелец именованной операции объявляет её имя для человека (ADR-0019 §5): идентификатор
 * стабилен и не выводится из подписи метода, а название живёт рядом с определением, потому что
 * только владелец знает, что операция делает.
 *
 * <p>Без этого админ-экран показывает ключ {@code ACTION:...} сырым, и администратор не может
 * объяснить, что именно он выдаёт. Название не участвует в решении и не влияет на права: оно
 * только называет операцию там, где её выдают.</p>
 */
public interface NamedOperationOwner {

    /** Стабильный идентификатор операции — тот же, что уходит в {@code C5PermissionKeys.action}. */
    String permissionId();

    /** Название операции для человека. */
    String title();
}
