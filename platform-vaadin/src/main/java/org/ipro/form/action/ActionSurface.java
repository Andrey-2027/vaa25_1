package org.ipro.form.action;

/**
 * Поверхность исполнения действия (E1.1): часть ключа регистрации.
 *
 * <p>Одно и то же {@link ActionId} может существовать на разных поверхностях с разными
 * условиями (например, {@code crud.refresh} в тулбаре списка и обновление в подвале карточки).
 * Поэтому поверхность входит в ключ {@code (surface, entityType, variant, actionId)}, а не
 * выводится из места рендера.</p>
 */
public enum ActionSurface {

    /** Тулбар списка. */
    LIST_TOOLBAR,

    /** Подвал карточки элемента. */
    ITEM_FOOTER,

    /** Меню элемента. */
    ITEM_MENU
}
