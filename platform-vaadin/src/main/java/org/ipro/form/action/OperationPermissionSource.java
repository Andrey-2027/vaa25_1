package org.ipro.form.action;

import org.ipro.data.DataOperation;

/**
 * Ответ на вопрос «разрешена ли эта операция типа текущему субъекту» (E1.2b): порт, через который
 * слой действий берёт общий ответ о правах, не зная, кто именно его считает.
 *
 * <p>Операция типа решается <b>один раз</b> и тем же движком, что спрашивает серверная граница
 * (C5, ADR-0017 §3). Слой действий не перечитывает хранилище грантов и не выводит право из
 * построчных измерений: построчный ответ остаётся у RLS ({@code RlsUiGate}) и складывается с этим
 * ответом в {@link ActionContextProvider} — в одном месте, а не в каждом host'е.</p>
 *
 * <p><b>Почему порт, а не прямой вызов C5.</b> Здесь назван только вопрос, а не его источник: так
 * провайдер входов решения остаётся проверяемым без хранилища грантов, а платформенная
 * авто-конфигурация подставляет реализацию поверх {@code C5PermissionDecisionService} —
 * того же сервиса, которым отвечает enforcement (именованные операции владельцев спрашивают его
 * напрямую, см. ADR-0019).</p>
 *
 * <p><b>Отказ обязан быть названным.</b> Возвращается безопасный для показа текст: без чужих
 * ключей, значений измерений и скрытых данных — как {@code C5DecisionReason#message()}. Порт не
 * умеет отвечать «права нет» без причины: молчаливый отказ в UI необъясним администратору.</p>
 */
@FunctionalInterface
public interface OperationPermissionSource {

    /**
     * @param entityType тип сущности, операция над которым оценивается
     * @param operation  операция записи ({@code CREATE}/{@code UPDATE}/{@code DELETE})
     * @return {@code null}, если операция разрешена; иначе безопасный для показа текст причины отказа
     */
    String denialReason(Class<?> entityType, DataOperation operation);
}
