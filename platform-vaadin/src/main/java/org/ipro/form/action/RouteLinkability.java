package org.ipro.form.action;

import org.ipro.form.link.NotLinkableReason;

import java.util.Objects;

/**
 * Вход решения об адресуемости формы (E2.1): построима ли ссылка на то, к чему относится действие.
 *
 * <p>То же место в решении, что {@link ActionPermission} занимает для прав: не «кнопка считает
 * ссылку сама», а <b>вход</b>, по которому чистая {@link ActionPolicy} выносит решение. Формула
 * «у типа вообще нет публичного адреса» без такого входа обязательно расползлась бы по хостам —
 * у списка, у подвала карточки и у меню элемента она была бы написана заново, а разойтись смогла
 * бы молча.</p>
 *
 * <p><b>Привязка выполняется до контекста, а не в решении.</b> Источник ответа — каталог адресов,
 * которому нужны вид формы ({@code records}/{@code lists}) и ключ варианта. И то, и другое
 * известно тому, кто собирает контекст ({@link ActionContextProvider}: список спрашивает про
 * {@code lists}, строка — про {@code records}). Поэтому решение получает уже привязанный вход:
 * политика не знает ни про поверхности, ни про грамматику адреса — она знает только «есть причина
 * отказа или нет».</p>
 *
 * <p><b>{@code null} — «адрес строится», а не «вход отсутствует».</b> Отсутствие входа — это
 * {@code null} в самом {@link ActionContext#linkability()}, и различать эти два случая
 * обязательно: действие, требующее адрес, на контексте без входа обязано упасть с названной
 * причиной композиции ({@link ActionPolicy}), а не молча спрятаться, выдав отсутствие адреса за
 * отсутствие настроенной платформы.</p>
 *
 * <p>Ответ — типизированная причина из {@code org.ipro.form.link}, а не флаг: решение обязано
 * уметь сказать, <i>почему</i> ссылки нет (тип не публикуется, сценарий чтения запрещён, вариант
 * требует необъявленного контекста), иначе пользователь получит «кнопки нет, потому что нет».</p>
 */
@FunctionalInterface
public interface RouteLinkability {

    /**
     * Причина, по которой адрес не строится, либо {@code null}, если он строится.
     *
     * <p>Вход <b>ленивый</b>: вызывается только действием, которое объявило требование адреса
     * ({@link ActionRequirement#requiresLinkable()}). Первое обращение к каталогу адресов строит
     * его, и платить за это решением о кнопке «Создать» незачем.</p>
     */
    NotLinkableReason notLinkable();

    /** Адрес строится: вход для контекста, у которого тип публикуется и вариант линкабелен. */
    static RouteLinkability linkable() {
        return () -> null;
    }

    /**
     * Адрес заведомо не строится — причина известна до обращения к каталогу.
     *
     * <p>Так выражается состояние, которое видно по самому контексту: у карточки, ещё не получившей
     * id, адреса записи не существует, и спрашивать каталог об этом значило бы описывать
     * несуществующую запись как адресную.</p>
     */
    static RouteLinkability blocked(NotLinkableReason reason) {
        Objects.requireNonNull(reason, "Причина неадресуемости не задана: «нет ссылки» без причины"
            + " неотличимо от «адресный вход не подключён»");
        return () -> reason;
    }
}
