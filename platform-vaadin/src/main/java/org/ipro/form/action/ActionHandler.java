package org.ipro.form.action;

/**
 * Прикладное действие списка (E1.6a): объявление и исполнение одной сущности.
 *
 * <p>Это app-facing половина машины действий: {@link ActionDefinition} описывает, <b>что</b> за
 * действие и при каких условиях оно доступно, а этот интерфейс — <b>как</b> оно выполняется.
 * Оба живут в одном бине, потому что объявление без исполнения не отличается от опечатки, а
 * исполнение без объявления — это снятый в E1.7 легаси-{@code ListCommand}, доступность которого
 * считалась предикатом внутри UI.</p>
 *
 * <p><b>Правило исполнителя:</b> доступность действия решает решение
 * ({@code capability + права + контекст}), а не предикат по форме. Если действие применимо не
 * всегда, это выражается требованием ({@link ActionRequirement}) — данными, которые проверяет
 * общая политика. Поэтому у исполнителя нет {@code isEnabled}: единственное, что он получает, —
 * уже принятое решение о запуске.</p>
 *
 * <p><b>Прикладной бин — не единственный способ.</b> Действие одного составного view может быть
 * объявлено локально на форме ({@code ListForm#addAction}) и тогда не требует ни Spring-бина, ни
 * центральной регистрации. Бин нужен для того, что переиспользуется списками или вариантами.</p>
 */
public interface ActionHandler {

    /** Объявление действия: идентичность, поверхность, тип, вариант и требование. */
    ActionDefinition definition();

    /**
     * Выполнить действие. Вызывается только тогда, когда решение разрешило запуск; повторную
     * проверку перед вызовом делает host, поэтому исполнение не обязано перепроверять права — но
     * обязано быть устойчивым к тому, что строка исчезла между решением и вызовом.
     */
    void execute(ActionInvocation invocation);
}
