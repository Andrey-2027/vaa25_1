package org.ipro.form.coordinator;

/**
 * Узнаёт об успешно открытой форме (APP_SPI). Приложение использует это, например, чтобы вести список
 * «Недавнее». Бинов может быть несколько или ни одного.
 *
 * <p>Событие приходит <b>после</b> открытия и только для успешного: отказ, «не найдено» и создание
 * новой записи его не дают. Исключение наблюдателя журналируется и не мешает открытию, поэтому
 * наблюдатель не может ни запретить, ни отменить открытие.</p>
 */
@FunctionalInterface
public interface FormOpenObserver {
    void opened(FormOpenEvent event);
}
