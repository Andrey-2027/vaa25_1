package org.ipro.form.link;

/**
 * Причина, по которой форма не получает публичную ссылку (E2.1, ADR-0009 §5).
 *
 * <p>Отсутствие ссылки — это <b>ответ</b>, а не пустая или битая ссылка: UI обязан показать
 * отсутствие affordance, а программный вызов — получить причину и не строить адрес, который
 * не откроется. Поэтому у каждой причины есть отдельное значение, а не «не получилось».</p>
 */
public enum NotLinkableReason {

    /**
     * Тип не публикуется: нет canonical handle ({@code OWNED_ROW}, {@code INTERNAL_STORE},
     * {@code UNCLASSIFIED}) либо его нет в каталоге. Строка секции открывается только внутри
     * агрегата, служебный storage — только владельцем подсистемы.
     */
    NOT_PUBLISHED,

    /**
     * Тип публикуется, но capability не даёт нужного сценария чтения:
     * {@code DETAIL} для карточки, {@code LIST} для списка.
     */
    SCENARIO_NOT_ALLOWED,

    /**
     * Список объявляет обязательный контекст-фильтр ({@code ContextFilterField.required*}),
     * а адрес в этой версии контекст не несёт. Такой список открывается только с явного
     * вызова; ссылка появится вместе с объявленным typed {@code RouteContextCodec}.
     */
    REQUIRED_CONTEXT,

    /** Карточка без id: адрес новой записи контрактом E2 не предусмотрен. */
    MISSING_ID,

    /** id вне грамматики (ноль, отрицательное значение): адрес такой записи не существует. */
    INVALID_ID,

    /** Список с id: id принадлежит карточке, а не списку. */
    UNEXPECTED_ID,

    /** Запрошенного варианта нет в {@code FormRegistry} для этой пары (тип, вид формы). */
    UNKNOWN_VARIANT
}
