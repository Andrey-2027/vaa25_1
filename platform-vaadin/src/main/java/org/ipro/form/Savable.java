package org.ipro.form;

/**
 * Форма/представление, которое умеет сохранять себя (кнопка «Сохранить и закрыть» в Workspace,
 * закрытие вкладки с несохранёнными изменениями).
 */
public interface Savable {

    boolean doSave();

    /**
     * Находится ли представление в режиме просмотра (E1.5).
     *
     * <p>Нужно host'у, предлагающему закрытие с сохранением: режим просмотра сохранения не
     * предлагает, потому что сохранять нечего, а «Сохранить и закрыть» на карточке просмотра —
     * это запись, которую сервер отклонит. Представления, у которых такого режима нет, остаются
     * на прежнем поведении: по умолчанию режима просмотра нет.</p>
     */
    default boolean isReadOnly() {
        return false;
    }
}
