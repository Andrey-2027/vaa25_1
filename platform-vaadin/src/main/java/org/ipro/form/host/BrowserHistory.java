package org.ipro.form.host;

import java.util.function.Consumer;

/**
 * История браузера, какой её видит мост адреса и вкладок (E2.3).
 *
 * <p>Отдельный тип нужен не ради «слоя», а ради проверяемости: {@code History} из Vaadin требует
 * живого UI и сеанса, поэтому без этой границы поведение моста (когда адрес меняется, а когда
 * нет, и что происходит на Back) проверялось бы только вручную в браузере. Здесь же остаётся
 * ровно три операции, и все решения моста тестируются без UI.</p>
 *
 * <p>{@code push} <b>добавляет</b> запись в историю, а не заменяет текущую: переключение вкладок
 * должно быть обратимо кнопкой Back — иначе «вернуться к записи, которую только что смотрел»
 * стало бы невозможно.</p>
 */
interface BrowserHistory {

    /**
     * Подписаться на переходы Back/Forward: аргумент — адрес, на который перешёл браузер.
     * Программные изменения адреса (наши же {@code push}) сюда не приходят.
     */
    void onBackForward(Consumer<String> handler);

    /** Добавить адрес в историю и сделать его текущим. */
    void push(String address);

    /**
     * Заменить текущую запись адресом и сделать его текущим, не добавляя шага в историю.
     *
     * <p>Нужно там, где возвращаться некуда: закрытая вкладка и переход на вкладку без адреса.
     * Оставить это как {@code push} значило бы предлагать Back к форме, которую пользователь
     * только что закрыл, — то есть возвращать в место, из которого он вышел осознанно.</p>
     */
    void replace(String address);
}
