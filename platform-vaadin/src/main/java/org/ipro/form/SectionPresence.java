package org.ipro.form;

/**
 * Фактическое состояние табличной части в текущей форме.
 *
 * <p>{@link #ATTACHED} означает, что секция действительно подключена к форме,
 * даже если в ней нет строк или она доступна только для чтения. {@link #ABSENT}
 * означает, что секция не входит в вариант формы и не должна участвовать в
 * загрузке, валидации или сохранении.</p>
 */
public enum SectionPresence {
    ATTACHED,
    ABSENT
}
