package org.ipro.form.spi;

import com.vaadin.flow.component.Component;

import java.util.function.Consumer;

/**
 * Платформенный контракт рабочей области (вкладки 1С-стиля).
 *
 * <p>Координатор открывает формы, не зная конкретный Workspace приложения: реализация — бин
 * <b>UI-scoped</b>, и координатор берёт её лениво, в момент открытия. Приложение не должно
 * «передавать» область куда-либо: наличие бина и есть включённый режим вкладок, а отсутствие —
 * работа в диалогах.</p>
 *
 * <p><b>Зачем здесь адрес (E2.3).</b> Мост адреса и вкладок живёт на платформе, но <i>какая</i>
 * вкладка активна и <i>что</i> показано вместо неё — знает только рабочая область. Поэтому
 * контракт отдаёт три вещи вместо одной: ключ активной вкладки, уведомление о её смене и
 * возможность активировать вкладку по ключу. Без них host не смог бы удержать адрес в
 * соответствии с видимым содержимым, не подсматривая реализацию.</p>
 */
public interface WorkspaceGateway {

    /** Открыть (или активировать существующую) вкладку с View-классом. */
    <T extends Component> void open(Class<T> viewType, String entryId,
                                    String tabTitle, Consumer<T> initializer);

    /** Открыть (или активировать существующую) вкладку с готовым компонентом. */
    void openComponent(Component view, String entryId, String tabTitle);

    /** Закрыть вкладку (с подтверждением при несохранённых изменениях — на стороне impl). */
    void close(String entryId);

    /**
     * Активировать уже открытую вкладку по ключу.
     *
     * <p>Отдельно от {@link #open}: активация не создаёт вкладку и не собирает форму, поэтому не
     * может быть выражена через {@code open}, которому нужен класс или компонент. Именно это
     * нужно переходу Back/Forward, где форма уже открыта и её повторная сборка была бы другим
     * действием.</p>
     *
     * @param entryId ключ вкладки; неизвестный ключ — ничего не делать, а не открывать пустую
     */
    void activate(String entryId);

    /** Ключ активной вкладки или {@code null}, если в рабочей области нет вкладок. */
    String activeEntryId();

    /**
     * Подписаться на смену активной вкладки: аргумент — её ключ либо {@code null}, когда вкладок
     * не осталось.
     *
     * <p>Уведомление обязано приходить и тогда, когда активная вкладка исчезла вместе с
     * закрытием: иначе адрес остался бы указывать на закрытую форму.</p>
     */
    void addActiveEntryListener(Consumer<String> listener);

    /**
     * Подписаться на закрытие вкладки: аргумент — ключ закрытой вкладки.
     *
     * <p>Отдельно от {@link #addActiveEntryListener}, потому что адрес обязан повести себя
     * по-разному: выбор другой вкладки <b>добавляет</b> запись в историю (Back возвращает
     * предыдущую), а закрытие активной вкладки — <b>заменяет</b> текущую (возвращаться к форме,
     * которую только что закрыли, некуда). Отличить эти два случая по смене активности нельзя:
     * видно только «активная вкладка стала другой».</p>
     */
    void addEntryClosedListener(Consumer<String> listener);

    /**
     * Показать компонент <b>вместо содержимого активной вкладки</b>, не создавая вкладку.
     *
     * <p>Нужно странице состояния адреса: у 403/404 нет ни формы, ни вкладки, но показать это
     * место нужно там, где пользователь ждёт содержимое, — иначе адрес, по которому ничего не
     * открылось, выглядел бы как рабочая форма. Показ не меняет активную вкладку, поэтому адрес
     * остаётся прежним; содержимое снимается при следующей активации вкладки.</p>
     */
    void showTransientContent(Component content);
}
