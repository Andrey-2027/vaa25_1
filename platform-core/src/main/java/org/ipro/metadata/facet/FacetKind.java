package org.ipro.metadata.facet;

/**
 * Вид грани метаданных, которую показывает Entity Explorer.
 *
 * <p>Классификация по П5 (docs/platform-forms-rules.md): переопределяемые грани — набор
 * роли 3 (подписи, видимость, членство в подсистемах, участие в поиске); структурные —
 * никогда не переопределяются в рантайме (поля/типы/FK/табличные части привязаны к схеме).</p>
 *
 * <p>{@code overridable() = true} означает: значение грани обязано резолвиться через
 * {@link FacetResolver} (код-дефолт ← переопределение), см. контракт-тест
 * EntityExplorerFacetContractTest. {@code overridable() = false} — грань показывается
 * как есть, пути переопределения у неё нет.</p>
 */
public enum FacetKind {

    // === Переопределяемые (роль 3, явно объявленные грани) ===

    /** Заголовок формы списка (@EntityMetadata.listFormTitle). */
    ENTITY_LIST_TITLE(true),

    /** Заголовок формы элемента (@EntityMetadata.itemFormTitle). */
    ENTITY_ITEM_TITLE(true),

    /** Заголовок формы выбора (@EntityMetadata.selectionFormTitle). */
    ENTITY_SELECTION_TITLE(true),

    /** Подпись поля формы (@FieldMetadata.label). */
    FIELD_LABEL(true),

    /** Заголовок колонки грида (дефолт — подпись поля или заголовок пути через точку). */
    GRID_COLUMN_HEADER(true),

    /** Подпись контекст-фильтра (ContextFilterField.label). */
    CONTEXT_FILTER_LABEL(true),

    /** Членство сущности в подсистеме (@EntityMetadata.subsystem). */
    SUBSYSTEM_MEMBERSHIP(true),

    // === Структурные (никогда не переопределяются в рантайме) ===

    /** Структура поля (имя, java-тип, обязательность, lookup-цель). */
    FIELD_STRUCTURE(false),

    /** Табличная часть документа (@TableSections/@TableSectionMetadata). */
    TABLE_SECTION(false),

    /** Lookup-цель поля (какая сущность открывается выбором). */
    LOOKUP_TARGET(false),

    /** Обратная ссылка «кто ссылается на сущность» (ReferenceIndex). */
    REVERSE_REFERENCE(false),

    /** Декларация нумеруемого поля (@Numbered). */
    NUMBERING_DECL(false),

    /** Эффективный semantic kind сущности. */
    ENTITY_KIND(false),

    /** Экспозиция сущности для стандартных операций платформы. */
    ENTITY_EXPOSURE(false),

    /** Внешний ключ Entity Explorer / Form Route. */
    ENTITY_KEY(false),

    /** Доступность ссылки на форму списка или элемента. */
    LINKABILITY(false),

    /** Наличие прикладного lifecycle handler. */
    ENTITY_LIFECYCLE_HANDLER(false),

    /** Отдельный lifecycle hook. */
    ENTITY_LIFECYCLE_HOOK(false),

    /**
     * Объявление действия на поверхности формы (E3.2.0): подпись, порядок, видимость.
     *
     * <p>Граней две, и это не удвоение: «действие объявлено» и «исполнитель найден» — разные
     * факты, как в lifecycle различимы handler и hook. Действие, объявленное платформой с
     * подавлением у типа, и действие с прикладным исполнителем различимы текстом, а не догадкой.</p>
     */
    ACTION(false),

    /**
     * Исполнитель действия (E3.2.0): найден ли обработчик для объявленного действия.
     *
     * <p>Отсутствие исполнителя не означает «действие не работает»: платформенные действия
     * обслуживаются встроенным путём формы, и карточка говорит это примечанием, а не пустой
     * ячейкой.</p>
     */
    ACTION_HANDLER(false),

    /**
     * Сценарий чтения сущности (E3.2.0 шаг 2): допускает ли canonical path сценарий и сколько
     * путей в его плане.
     *
     * <p>Происхождение строки — происхождение <b>набора</b> сценариев: объявлен приложением
     * ({@code REGISTRATION}) или выведен правилом экспозиции ({@code PLATFORM_DEFAULT}). Набор,
     * совпавший с правилом, остаётся объявлением: override заменяет выведенное, а не дополняет его.</p>
     */
    FETCH_PLAN(false),

    /**
     * Путь плана сценария (E3.2.0 шаг 2): адрес — «сценарий/путь», причина — из плана.
     *
     * <p>Граней две, и это не удвоение: «какие сценарии у типа» и «какие пути несёт план» —
     * разные факты, у второго всегда {@code DERIVED}: путь выведен из metadata и объявлений,
     * а не переопределён.</p>
     */
    FETCH_PLAN_PATH(false),

    /**
     * Измерение RLS на типе (E3.2.0 шаг 3): род измерения, служит ли оно каталогом грантов и где
     * объявлено.
     *
     * <p>Происхождение строки — {@code EXPLICIT}: измерение объявлено аннотацией на
     * классе-носителе, наследования измерений нет и «выведенного из {@code valuePaths}» измерения
     * не существует. Носитель не всегда сущность: у измерений-ворот это вложенный
     * интерфейс-маркер ({@code Subsystems.Directories}, {@code ReportRights.JpqlPreview}), и такой
     * факт принадлежит маркеру, а не сущности.</p>
     *
     * <p>Грань структурная: значения грантов и результат проверки по конкретной записи — данные и
     * решения, а не конфигурация типа, и в этой грани они не публикуются.</p>
     */
    RLS_DIMENSION(false),

    /**
     * Правило значения измерения RLS (E3.2.0 шаг 3): объявленные пути и то, что null означает
     * «измерение к записи не применимо».
     *
     * <p>У сложной политики ({@code custom = true}) строк правила <b>нет</b>, хотя атрибут
     * {@code valuePaths} в записи правила присутствует (дефолт аннотации): фильтрация идёт по
     * объявленному {@code readCondition}, а значения поставляет запись через
     * {@code RlsDimensionValue}. Показать этот дефолт как действующий путь значило бы выдать
     * недействующий атрибут за правило фильтрации, поэтому у custom-измерения адреса правила нет.</p>
     */
    RLS_VALUE_RULE(false);

    private final boolean overridable;

    FacetKind(boolean overridable) {
        this.overridable = overridable;
    }

    public boolean overridable() {
        return overridable;
    }
}
