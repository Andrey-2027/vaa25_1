package org.ipro.fetch.instance;

/**
 * Единственный контракт отображаемого имени сущности (C3.7, см. ADR-0006).
 *
 * <p>Это публичный API платформы для всего, что показывает сущность пользователю: грид,
 * поле выбора, табличная часть, глобальный поиск, аудит/снимок, телеметрия. Потребители
 * обязаны зависеть от этого интерфейса, а не от {@link InstanceNameResolver}: конкретная
 * реализация — деталь конфигурации, а состав имени — предметная декларация
 * {@link InstanceName}.</p>
 *
 * <p>Контракт {@link #resolve(Object)}: возвращает готовое к показу представление и
 * <b>никогда</b> не инициирует загрузку из БД — ни для неинициализированного Hibernate
 * proxy, ни после закрытия сессии. Порядок разрешения зафиксирован в
 * {@link InstanceNameResolver} (декларация → legacy {@code HasDisplayName} → безопасный
 * {@code Type#id}) и не должен дублироваться у потребителей: вторая лестница неизбежно
 * расходится с первой — ровно так и возник `LazyInitializationException` на detached
 * ссылке в UI-канале, который обходил proxy-safe реализацию.</p>
 */
@FunctionalInterface
public interface InstanceNameProvider {

    /**
     * Представление сущности для показа: {@code ""} для {@code null}, имя декларации, имя
     * legacy-интерфейса или безопасная ссылка {@code Type#id}. Никогда не бросает
     * {@code LazyInitializationException} и не порождает SQL.
     */
    String resolve(Object entity);
}
