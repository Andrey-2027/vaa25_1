package org.ipro.crud;

import org.ipro.data.DataOperation;

/**
 * Узкий preflight агрегата: право на операцию корня проверяется до aggregate-событий и
 * пользовательских хуков (ADR-0017 §5, план C5.6).
 *
 * <p>Контракт намеренно узкий: проверяется пара (тип корня, операция) и ничего больше.
 * Строки owned-секций наследуют допуск корня, а построчные проверки остаются у RLS и у
 * секционных writer'ов. Вызов не выполняет ни SQL мутации, ни нумерации, ни валидации —
 * он только отвечает на вопрос о праве.</p>
 *
 * <p>Отсутствие авторизатора не расширяет права: canonical save внутри агрегата проверяет то
 * же решение сам и откажет без гранта — просто позже, после aggregate-хуков. Именно поэтому
 * seam опционален, а не обязателен: обязательным остаётся решение, а не место вызова.</p>
 */
@FunctionalInterface
public interface AggregateOperationAuthorizer {

    /** Требует право на операцию корня агрегата; отказ выражается security-исключением. */
    void requireOperation(Class<?> aggregateType, DataOperation operation);
}
