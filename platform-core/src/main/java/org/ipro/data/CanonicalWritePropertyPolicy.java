package org.ipro.data;

/**
 * Владелец свойства, которое generic-запись не переносит: изменение такого свойства обязано быть
 * авторизовано именованной операцией владельца, а не правом на изменение строки (ADR-0019 §1/§2
 * по форме, ADR-0017 §12 по словарю операций).
 *
 * <p><b>Это не полевое право.</b> Ни ATTR-ключей, ни флагов на отдельные поля здесь не
 * появляется (ADR-0018): спрашивается то же самое решение C5 об именованной операции владельца,
 * которое уже принимается на серверном пути, — просто в момент записи, несущей изменение
 * свойства. Владелец объявляет правило один раз на тип, и ни один канал canonical write не может
 * его пропустить: и generic update/save, и именованная операция проходят через preflight.</p>
 *
 * <p><b>Когда спрашивается.</b> Preflight canonical write передаёт предсостояние строки
 * (у update оно уже загружено для RLS исходного состояния; у create его нет — {@code null}) и
 * цель записи. Реализация решает, изменилось ли её свойство, и требует своё право: отказ приходит
 * до нумерации, валидации, хуков, событий и SQL-мутации, как и всякий другой отказ операции.</p>
 *
 * <p><b>Отсутствие политики — не ослабление.</b> Зарегистрированной политики нет у типов, у
 * которых таких свойств нет; границы самого типа (capability и C5-решение об операции) остаются
 * обязательными всегда. Реализация обязана сама ничего не разрешать: она только требует право,
 * когда его свойство тронуто.</p>
 */
public interface CanonicalWritePropertyPolicy {

    /**
     * Требует авторизацию именованной операции, если запись несёт изменение защищённого свойства.
     *
     * @param type     заявленный тип записи (тот же, по которому решены capability и операция)
     * @param original предсостояние строки; {@code null} при создании — предсостояния нет
     * @param target   записываемое состояние (сущность для merge либо строка после мутации
     *                 владельца при именованной операции)
     */
    void requireAuthorizedChange(Class<?> type, Object original, Object target);
}
