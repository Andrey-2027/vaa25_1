package org.ipro.query.model;

/**
 * Откуда берётся исполняемый текст запроса.
 *
 * <p>{@link #MANUAL} — первичен JPQL; визуальное представление отсутствует или
 * является производным. {@link #VISUAL} — первично визуальное описание, а JPQL
 * строится компилятором. Это различие должно решаться явно, а не угадываться по
 * непустому JSON: две расходящиеся истины недопустимы.</p>
 */
public enum QuerySource {
    MANUAL,
    VISUAL
}
