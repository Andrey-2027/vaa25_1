[CmdletBinding()]
param(
    [string]$PostgresBin = 'C:\Program Files\PostgreSQL\17\bin',
    [string]$JavaHome = 'C:\Program Files\Axiom\AxiomJDK-21'
)
Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
$taskRoot = Split-Path $PSScriptRoot -Parent
Push-Location -LiteralPath $taskRoot
$taskOutput = Join-Path $taskRoot 'outputs/et8'
$et8Settings = @{}
Get-Content -LiteralPath 'config/application-local.properties' | ForEach-Object {
    if ($_ -match '^([^#=]+)=(.*)$') { $et8Settings[$matches[1].Trim()] = $matches[2].Trim() }
}
if ($et8Settings['spring.datasource.url'] -notmatch '^jdbc:postgresql://(localhost|127\.0\.0\.1):(\d+)/([A-Za-z0-9_]+)$') {
    throw 'Expected configured local PostgreSQL URL.'
}
$et8Host=$matches[1]; $et8Port=$matches[2]; $et8ExistingDatabase=$matches[3]
$et8Database='et8_interning_' + [Guid]::NewGuid().ToString('N')
if ($et8Database -notmatch '^et8_interning_[a-f0-9]{32}$') { throw 'Invalid isolated database name.' }
$et8Saved=@{}
$et8Variables=@('PGPASSWORD','SPRING_DATASOURCE_URL','SPRING_DATASOURCE_USERNAME','SPRING_DATASOURCE_PASSWORD',
    'SPRING_DATASOURCE_DRIVER_CLASS_NAME','SPRING_JPA_DATABASE_PLATFORM','SPRING_TEST_DATABASE_REPLACE')
foreach ($name in $et8Variables) { $et8Saved[$name]=[Environment]::GetEnvironmentVariable($name,'Process') }
$et8Created=$false
try {
    $env:PGPASSWORD=$et8Settings['spring.datasource.password']
    $connection=@('-h',$et8Host,'-p',$et8Port,'-U',$et8Settings['spring.datasource.username'],'-w','-X','-v','ON_ERROR_STOP=1')
    & (Join-Path $PostgresBin 'psql.exe') @connection '-d' $et8ExistingDatabase '-f' 'scripts/entity-types-et8/schema-check.sql' *> "$taskOutput/postgres-applied-schema.log"
    if ($LASTEXITCODE -ne 0) { throw 'Applied schema mismatch; see postgres-applied-schema.log.' }
    & (Join-Path $PostgresBin 'psql.exe') @connection '-d' 'postgres' '-c' "CREATE DATABASE $et8Database" *> "$taskOutput/postgres-create.log"
    if ($LASTEXITCODE -ne 0) { throw 'Isolated database creation failed.' }
    $et8Created=$true
    $env:SPRING_DATASOURCE_URL="jdbc:postgresql://${et8Host}:${et8Port}/$et8Database"
    $env:SPRING_DATASOURCE_USERNAME=$et8Settings['spring.datasource.username']
    $env:SPRING_DATASOURCE_PASSWORD=$et8Settings['spring.datasource.password']
    $env:SPRING_DATASOURCE_DRIVER_CLASS_NAME='org.postgresql.Driver'
    $env:SPRING_JPA_DATABASE_PLATFORM='org.hibernate.dialect.PostgreSQLDialect'
    $env:SPRING_TEST_DATABASE_REPLACE='none'
    $runtime=(Get-Content "$taskOutput/runtime-classpath.txt" -Raw).Trim()
    $argsFile=@('--release','21','-parameters','-encoding','UTF-8','-cp',('"'+$runtime.Replace('\','/')+'"'),
        '-sourcepath','src/test/java','-d','outputs/et8/app-test-classes','src/test/java/org/ipro/crud/InternedPostgresIT.java')
    [IO.File]::WriteAllLines("$taskOutput/postgres-compile.args",[string[]]$argsFile,[Text.UTF8Encoding]::new($false))
    & (Join-Path $JavaHome 'bin/javac.exe') ('@'+"$taskOutput/postgres-compile.args") *> "$taskOutput/postgres-compile.log"
    if ($LASTEXITCODE -ne 0) { throw 'PostgreSQL tests compilation failed.' }
    $agent=@((Get-Content "$taskOutput/classpath.txt" -Raw).Trim() -split ';' | Where-Object { (Split-Path $_ -Leaf) -like 'mockito-core-*.jar' })
    & (Join-Path $JavaHome 'bin/java.exe') '-Dfile.encoding=UTF-8' ('-javaagent:'+$agent[0]) `
        '-Dspring.test.database.replace=none' '-cp' $runtime Et8Checks org.ipro.crud.InternedPostgresIT `
        org.ip.service.AttributeValueServiceTest org.ip.service.SklNomOpaServiceTest *> "$taskOutput/postgres-tests.log"
    if ($LASTEXITCODE -ne 0) { Get-Content "$taskOutput/postgres-tests.log" -Tail 60; throw 'PostgreSQL ET8 acceptance failed.' }
    [ordered]@{ stage='ET8'; postgres=$true; appliedSchemaVerified=$true; isolatedDatabase=$et8Database; passed=$true } |
        ConvertTo-Json | Set-Content "$taskOutput/postgres-receipt.json" -Encoding utf8
    Write-Output 'ET8 PostgreSQL schema, forced races, rollback and real service regression passed.'
} finally {
    if ($et8Created) {
        # Only the database generated by this invocation is eligible for cleanup.
        & (Join-Path $PostgresBin 'psql.exe') @connection '-d' 'postgres' '-c' "DROP DATABASE $et8Database" *> "$taskOutput/postgres-cleanup.log"
        if ($LASTEXITCODE -ne 0) { Write-Warning "Isolated database cleanup failed: $et8Database" }
    }
    foreach ($name in $et8Variables) { [Environment]::SetEnvironmentVariable($name,$et8Saved[$name],'Process') }
    Pop-Location
}
