package com.example.generated.harness;

import com.example.Item;
import com.vaadin.flow.component.page.AppShellConfigurator;
import com.vaadin.flow.spring.annotation.EnableVaadin;
import com.vaadin.flow.spring.security.VaadinSecurityConfigurer;
import java.util.List;
import java.util.Optional;
import org.ipro.data.EntityDataAccess;
import org.ipro.register.RegisterRegistry;
import org.ipro.register.RegisterKeyWritePermissions;
import org.ipro.rls.AccessGrant;
import org.ipro.rls.AccessGrantRepository;
import org.ipro.rls.RlsCurrentUser;
import org.ipro.rls.c5.C5PermissionKeys;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.boot.CommandLineRunner;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;
import org.springframework.context.annotation.Profile;
import org.springframework.data.domain.AuditorAware;
import org.springframework.data.domain.PageRequest;
import org.springframework.data.jpa.repository.config.EnableJpaAuditing;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.security.authentication.UsernamePasswordAuthenticationToken;
import org.springframework.security.config.annotation.web.builders.HttpSecurity;
import org.springframework.security.core.authority.SimpleGrantedAuthority;
import org.springframework.security.core.context.SecurityContextHolder;
import org.springframework.security.core.userdetails.User;
import org.springframework.security.core.userdetails.UserDetailsService;
import org.springframework.security.provisioning.InMemoryUserDetailsManager;
import org.springframework.security.web.SecurityFilterChain;

@Configuration(proxyBeanMethods = false)
@Profile("acceptance-ui")
@EnableVaadin("com.example.generated.harness")
@EnableJpaAuditing
public class AcceptanceUiConfiguration implements AppShellConfigurator {
    @Bean UserDetailsService acceptanceUsers() {
        var users = new InMemoryUserDetailsManager();
        for (String name : List.of("admin", "writer", "reader", "denied", "generic-writer")) {
            users.createUser(User.withUsername(name).password("{noop}acceptance-local-only")
                .roles(name.equals("admin") ? "ADMIN" : "USER").build());
        }
        return users;
    }
    @Bean SecurityFilterChain acceptanceSecurity(HttpSecurity http) throws Exception {
        return http.with(VaadinSecurityConfigurer.vaadin(), v -> v.loginView(AcceptanceLogin.class)).build();
    }
    @Bean AuditorAware<String> acceptanceAuditor(RlsCurrentUser current) {
        return () -> Optional.ofNullable(current.username());
    }
    @Bean AcceptanceStores acceptanceStores(JdbcTemplate jdbc, RlsCurrentUser user) {
        return new AcceptanceStores(jdbc, user);
    }
    @Bean CommandLineRunner acceptanceSeed(AccessGrantRepository grants, EntityDataAccess data,
            RegisterRegistry registry, org.ipro.register.RegisterKeyWrites writes,
            JdbcTemplate jdbc, @Value("${acceptance.initialize:false}") boolean initialize) {
        return args -> {
            if (!initialize) {
                jdbc.queryForObject("select count(*) from acceptance_form_settings", Long.class);
                jdbc.queryForObject("select count(*) from acceptance_grid_views", Long.class);
                return;
            }
            jdbc.execute("create table acceptance_form_settings (owner_name varchar(200), setting_key varchar(1000), setting_value clob, primary key(owner_name, setting_key))");
            jdbc.execute("create table acceptance_grid_views (id bigint generated by default as identity primary key, form_key varchar(1000), view_name varchar(200), columns_json clob, shared boolean, owner_name varchar(200))");
            SecurityContextHolder.getContext().setAuthentication(UsernamePasswordAuthenticationToken.authenticated(
                "admin", null, List.of(new SimpleGrantedAuthority("ROLE_ADMIN"))));
            try {
                var types = new java.util.ArrayList<Class<?>>(); types.add(Item.class); types.add(com.example.Region.class);
                registry.descriptors().forEach(d -> types.add(d.entityType()));
                for (var type : types) {
                    for (var name : List.of("admin", "writer", "generic-writer", "reader")) {
                        grant(grants, name, C5PermissionKeys.entity(type), true, !name.equals("reader"));
                    }
                    if (type != Item.class) for (var name : List.of("admin", "writer")) {
                        grant(grants, name, C5PermissionKeys.action(RegisterKeyWritePermissions.setPermissionId(type)), false, true);
                        grant(grants, name, C5PermissionKeys.action(RegisterKeyWritePermissions.deletePermissionId(type)), false, true);
                    }
                }
                if (data.list(Item.class, null, PageRequest.of(0, 1)).isEmpty()) {
                    for (String name : List.of("Товар A", "Товар B")) {
                        var item = new Item(); item.setName(name); data.create(Item.class, item);
                    }
                }
                if (data.list(com.example.Region.class, null, PageRequest.of(0,1)).isEmpty()) {
                    for(String name:List.of("Регион A","Регион B")) {
                        var region=new com.example.Region();region.setName(name);data.create(com.example.Region.class,region);
                    }
                }
                for(var descriptor:registry.descriptors()) for(var policy:descriptor.entityType().getAnnotationsByType(org.ipro.rls.RlsDimension.class)) {
                    var fieldName=policy.valuePaths()[0].substring(0,policy.valuePaths()[0].indexOf('.'));
                    var reference=descriptor.entityType().getDeclaredField(fieldName).getType();
                    var first=(org.ipro.crud.BaseEntity)data.list((Class)reference,null,PageRequest.of(0,1,org.springframework.data.domain.Sort.by("id"))).getContent().getFirst();
                    rowGrant(grants,"admin",policy.value(),null,true);
                    rowGrant(grants,"writer",policy.value(),first.getId(),true);
                    rowGrant(grants,"generic-writer",policy.value(),first.getId(),true);
                    rowGrant(grants,"reader",policy.value(),first.getId(),false);
                    var references=data.list((Class)reference,null,PageRequest.of(0,10,org.springframework.data.domain.Sort.by("id"))).getContent();
                    for(int i=0;i<references.size();i++) {
                        var ref=(org.ipro.crud.BaseEntity)references.get(i);
                        var key=java.util.Map.<String,Object>of(fieldName,ref.getId());
                        writes.set((Class)descriptor.entityType(),key,java.util.Map.of("rate",java.math.BigDecimal.valueOf(11L*(i+1))),
                            descriptor.periodic()?java.time.LocalDateTime.of(2026,11,1,0,0):null);
                        if(descriptor.periodic()) writes.set((Class)descriptor.entityType(),key,
                            java.util.Map.of("rate",java.math.BigDecimal.valueOf(33L*(i+1))),java.time.LocalDateTime.of(2026,11,2,0,0));
                    }
                }
            } finally { SecurityContextHolder.clearContext(); }
        };
    }
    private static void grant(AccessGrantRepository repository, String user, String dimension, boolean read, boolean write) {
        var grant = new AccessGrant(); grant.setSubjectType(AccessGrant.SubjectType.USER); grant.setSubjectKey(user);
        grant.setDimension(dimension); grant.setCanRead(read); grant.setCanUpdate(write); grant.setCanDelete(write);
        repository.saveAndFlush(grant);
    }
    private static void rowGrant(AccessGrantRepository repository,String user,String dimension,Long id,boolean write) {
        var grant=new AccessGrant();grant.setSubjectType(AccessGrant.SubjectType.USER);grant.setSubjectKey(user);
        grant.setDimension(dimension);grant.setDimensionValueId(id);grant.setCanRead(true);grant.setCanUpdate(write);grant.setCanDelete(write);
        repository.saveAndFlush(grant);
    }
}
