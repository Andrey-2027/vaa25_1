-- Pilot 1. Apply once to the isolated pilot database, before ddl-auto=validate.
BEGIN;
CREATE TABLE accounting_type (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version bigint,
    created_at timestamp(6), modified_at timestamp(6),
    created_by varchar(255), modified_by varchar(255),
    code varchar(20) NOT NULL UNIQUE, name varchar(100) NOT NULL
);
CREATE TABLE accounting_object_installation (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version bigint,
    created_at timestamp(6), modified_at timestamp(6),
    created_by varchar(255), modified_by varchar(255),
    number varchar(30) NOT NULL UNIQUE,
    document_date timestamp(6) NOT NULL,
    workshop_id bigint NOT NULL REFERENCES workshop(id)
);
CREATE TABLE accounting_object_installation_item (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version bigint,
    created_at timestamp(6), modified_at timestamp(6),
    created_by varchar(255), modified_by varchar(255),
    document_id bigint NOT NULL REFERENCES accounting_object_installation(id),
    line_number integer NOT NULL,
    nomenclature_id bigint NOT NULL REFERENCES nomenclature(id),
    accounting_type_id bigint NOT NULL REFERENCES accounting_type(id)
);
CREATE INDEX ix_accounting_installation_items ON accounting_object_installation_item(document_id);
CREATE TABLE accounting_object_correction (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version bigint,
    created_at timestamp(6), modified_at timestamp(6),
    created_by varchar(255), modified_by varchar(255),
    number varchar(30) NOT NULL UNIQUE,
    document_date timestamp(6) NOT NULL,
    workshop_id bigint NOT NULL REFERENCES workshop(id)
);
CREATE TABLE accounting_object_correction_item (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version bigint,
    created_at timestamp(6), modified_at timestamp(6),
    created_by varchar(255), modified_by varchar(255),
    document_id bigint NOT NULL REFERENCES accounting_object_correction(id),
    line_number integer NOT NULL,
    nomenclature_id bigint NOT NULL REFERENCES nomenclature(id),
    accounting_type_id bigint NOT NULL REFERENCES accounting_type(id),
    current_accounting_type_id bigint REFERENCES accounting_type(id)
);
CREATE INDEX ix_accounting_correction_items ON accounting_object_correction_item(document_id);
CREATE TABLE nomenclature_accounting_object (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version bigint,
    created_at timestamp(6), modified_at timestamp(6),
    created_by varchar(255), modified_by varchar(255),
    recorder_type varchar(64) NOT NULL,
    recorder_id bigint NOT NULL,
    line_no integer NOT NULL CHECK (line_no > 0),
    recording_order bigint NOT NULL CHECK (recording_order > 0),
    period_date timestamp(6) NOT NULL,
    workshop_id bigint NOT NULL REFERENCES workshop(id),
    nomenclature_id bigint NOT NULL REFERENCES nomenclature(id),
    accounting_type_id bigint NOT NULL REFERENCES accounting_type(id),
    CONSTRAINT uk_accounting_object_recorder UNIQUE(recorder_type, recorder_id, line_no)
);
CREATE INDEX ix_accounting_object_slice ON nomenclature_accounting_object
    (workshop_id,nomenclature_id,period_date,recording_order,line_no);
CREATE INDEX ix_accounting_object_recorder ON nomenclature_accounting_object(recorder_type,recorder_id);
COMMIT;

