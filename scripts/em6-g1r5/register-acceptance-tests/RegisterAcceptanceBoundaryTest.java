/** Additional A2/A3/A4 evidence on the actual applied class and frozen backend JARs. */
@Import(RegisterAcceptanceBoundaryTest.EvidenceConfiguration.class)
@SuppressWarnings({"rawtypes", "unchecked"})
class RegisterAcceptanceBoundaryTest extends RegisterScenarioTest {
    static final LocalDateTime FIRST=LocalDateTime.of(2026,11,1,14,35);
    @Autowired JdbcTemplate jdbc;
    @Autowired PlatformTransactionManager transactionManager;
    @Autowired EvidenceSink sink;
    @PersistenceContext EntityManager managed;

    @BeforeEach void prepareEvidence() {
        jdbc.execute("create table if not exists ACCEPTANCE_BOUNDARY_AUDIT (ID bigint generated by default as identity primary key, ENTITY_NAME varchar(255), ROW_ID varchar(255), VERB varchar(40), PAYLOAD clob)");
        jdbc.update("delete from ACCEPTANCE_BOUNDARY_AUDIT");
        sink.events.clear(); sink.attempts=0;
    }

    @Test void checkedAbsenceStaleVersionsAndRepeatedSetHaveNoExtraEffects() throws Exception {
        var key=key(); var period=period(FIRST);
        assertThat(writes.set(type,key,Map.of("rate",BigDecimal.ONE),period,0L).verdict()).isEqualTo(RegisterKeyWrites.Verdict.ABSENT);
        assertThat(writes.delete(type,key,period,0L).verdict()).isEqualTo(RegisterKeyWrites.Verdict.ABSENT);
        assertThat(audits()).isZero(); assertThat(targetEvents()).isZero();
        var created=writes.set(type,key,Map.of("rate",new BigDecimal("10.00")),period);
        var row=(BaseEntity)created.row(); var original=state(row.getId());
        assertThat(audits()).isEqualTo(1); assertThat(targetEvents()).isEqualTo(1);
        int attempts=sink.attempts;
        assertThat(writes.set(type,key,Map.of("rate",BigDecimal.TEN),period,row.getVersion()).verdict()).isEqualTo(RegisterKeyWrites.Verdict.UNCHANGED);
        assertThat(writes.set(type,key,Map.of("rate",BigDecimal.valueOf(99)),period,row.getVersion()+7).verdict()).isEqualTo(RegisterKeyWrites.Verdict.VERSION_CONFLICT);
        assertThat(writes.delete(type,key,period,null).verdict()).isEqualTo(RegisterKeyWrites.Verdict.VERSION_REQUIRED);
        assertThat(writes.delete(type,key,period,row.getVersion()+7).verdict()).isEqualTo(RegisterKeyWrites.Verdict.VERSION_CONFLICT);
        assertThat(state(row.getId())).isEqualTo(original);
        assertThat(audits()).isEqualTo(1); assertThat(targetEvents()).isEqualTo(1); assertThat(sink.attempts).isEqualTo(attempts);
        assertThat(writes.delete(type,key,period,row.getVersion()).verdict()).isEqualTo(RegisterKeyWrites.Verdict.DELETED);
        assertThat(writes.delete(type,key,period,row.getVersion()).verdict()).isEqualTo(RegisterKeyWrites.Verdict.ABSENT);
        assertThat(audits()).isEqualTo(2); assertThat(targetEvents()).isEqualTo(2);
    }

    @Test void rolledBackSetAndDeleteKeepRowsVersionsAuditAndCommittedEvents() throws Exception {
        var key=key();var period=period(FIRST);
        var row=(BaseEntity)writes.set(type,key,Map.of("rate",BigDecimal.TEN),period).row();
        var original=state(row.getId()); int attempts=sink.attempts;
        var transactions=new TransactionTemplate(transactionManager);
        transactions.executeWithoutResult(tx->{
            assertThat(writes.set(type,key,Map.of("rate",BigDecimal.valueOf(91)),period,row.getVersion()).verdict()).isEqualTo(RegisterKeyWrites.Verdict.UPDATED);
            tx.setRollbackOnly();
        });
        assertThat(sink.attempts).isGreaterThan(attempts);
        assertThat(state(row.getId())).isEqualTo(original);
        assertThat(audits()).isEqualTo(1);assertThat(targetEvents()).isEqualTo(1);
        transactions.executeWithoutResult(tx->{
            assertThat(writes.delete(type,key,period,row.getVersion()).verdict()).isEqualTo(RegisterKeyWrites.Verdict.DELETED);
            tx.setRollbackOnly();
        });
        assertThat(state(row.getId())).isEqualTo(original);
        assertThat(audits()).isEqualTo(1);assertThat(targetEvents()).isEqualTo(1);
    }

    @Test void managedKeyMutationIsRejectedWithoutDurableEffects() throws Exception {
        var row=(BaseEntity)writes.set(type,key(),Map.of("rate",BigDecimal.TEN),period(FIRST)).row();
        var original=state(row.getId()); var other=dimension();
        long count=audits();long events=targetEvents();
        assertThatThrownBy(()->new TransactionTemplate(transactionManager).executeWithoutResult(tx->{
            Object current=managed.find(type,row.getId());
            try {
                if(ScenarioSpec.PERIODIC)((PeriodicRegisterEntryBase)current).setPeriod(FIRST.plusDays(1));
                else {var field=type.getDeclaredField(ScenarioSpec.DIMENSION);field.setAccessible(true);field.set(current,other);}
                type.getMethod("setRate",BigDecimal.class).invoke(current,BigDecimal.valueOf(99));
                managed.flush();
            } catch(ReflectiveOperationException failure){throw new IllegalStateException(failure);}
        })).hasStackTraceContaining("REGISTER_KEY_CHANGE_REQUIRED");
        assertThat(state(row.getId())).isEqualTo(original);
        assertThat(audits()).isEqualTo(count);assertThat(targetEvents()).isEqualTo(events);
    }

    @Test void temporalBoundaryBatchAndSameDayNormalizationMatchTheAppliedModel() throws Exception {
        if(!ScenarioSpec.PERIODIC){
            assertThatThrownBy(()->readers.point(type)).isInstanceOf(IllegalArgumentException.class);
            assertThatThrownBy(()->readers.slice(type)).isInstanceOf(IllegalArgumentException.class);return;
        }
        var key=key();var second=FIRST.plusDays(1);
        var first=(BaseEntity)writes.set(type,key,Map.of("rate",BigDecimal.TEN),FIRST).row();
        writes.set(type,key,Map.of("rate",BigDecimal.valueOf(20)),second);
        var midnight=FIRST.toLocalDate().atStartOfDay();
        var point=readers.point(type);
        // Point reader accepts mapped dimension values; named writes and slice batch accept reference IDs.
        var pointKey=Map.of(ScenarioSpec.DIMENSION,data.detail(Class.forName(ScenarioSpec.DIMENSION_TYPE),key.get(ScenarioSpec.DIMENSION)).orElseThrow());
        assertThat(point.getLast(pointKey,midnight.minusNanos(1))).isEmpty();
        assertThat(point.getLast(pointKey,midnight)).hasValueSatisfying(r->assertThat(amount(r)).isEqualByComparingTo("10"));
        assertThat(point.getLast(pointKey,second.toLocalDate().atStartOfDay())).hasValueSatisfying(r->assertThat(amount(r)).isEqualByComparingTo("20"));
        assertThat(readers.slice(type).latestForKeys(midnight,List.of(key))).hasSize(1);
        assertThat(readers.slice(type).latestForKeys(midnight.minusNanos(1),List.of(key))).isEmpty();
        Object current=data.detail(type,first.getId()).orElseThrow();
        ((PeriodicRegisterEntryBase)current).setPeriod(midnight.plusHours(23));
        data.update(type,(BaseEntity)current);
        assertThat(((PeriodicRegisterEntryBase)data.detail(type,first.getId()).orElseThrow()).getPeriod()).isEqualTo(midnight);
    }

    private Object dimension() throws Exception {
        if(ScenarioSpec.DIMENSION_TYPE.equals("java.lang.String"))return "AC-"+UUID.randomUUID().toString().substring(0,8);
        var reference=(StandardCatalogEntity)Class.forName(ScenarioSpec.DIMENSION_TYPE).getDeclaredConstructor().newInstance();
        reference.setCode("AC-"+UUID.randomUUID().toString().substring(0,8));reference.setName("Acceptance boundary reference");
        return data.create((Class)reference.getClass(),reference);
    }
    private Map<String,Object> key() throws Exception {
        Object value=dimension();
        return Map.of(ScenarioSpec.DIMENSION,value instanceof BaseEntity entity?entity.getId():value);
    }
    private LocalDateTime period(LocalDateTime value){return ScenarioSpec.PERIODIC?value:null;}
    private BigDecimal amount(Object row){try{return (BigDecimal)type.getMethod("getRate").invoke(row);}catch(Exception e){throw new IllegalStateException(e);}}
    private Map<String,Object> state(Long id) {
        var table=registry.require(type).entityType().getAnnotation(jakarta.persistence.Table.class).name();
        return jdbc.queryForMap("select * from "+table+" where id=?",id);
    }
    private long audits(){return jdbc.queryForObject("select count(*) from ACCEPTANCE_BOUNDARY_AUDIT where ENTITY_NAME=?",Long.class,type.getSimpleName());}
    private long targetEvents(){return sink.events.stream().filter(e->type.isInstance(e)).count();}

    @TestConfiguration(proxyBeanMethods=false) static class EvidenceConfiguration {
        @Bean @Primary EvidenceSink acceptanceBoundarySink(JdbcTemplate jdbc){return new EvidenceSink(jdbc);}
    }
    static class EvidenceSink implements EventSink {
        final JdbcTemplate jdbc;final List<Object> events=new ArrayList<>();int attempts;
        EvidenceSink(JdbcTemplate jdbc){this.jdbc=jdbc;}
        @EventListener public void changed(EntityChangedEvent<?> event){events.add(event.entity());}
        @EventListener public void deleted(EntityDeletedEvent<?> event){events.add(event.entity());}
        public void accept(TelemetryEvent event){}
        public void acceptDurable(TelemetryEvent event){}
        public void acceptStats(AggregateStats stats){}
        public void flush(){}
        public void acceptFieldChangeDurable(FieldChangeRecord record){
            attempts++;
            jdbc.update("insert into ACCEPTANCE_BOUNDARY_AUDIT(ENTITY_NAME,ROW_ID,VERB,PAYLOAD) values (?,?,?,?)",record.entity(),record.entityId(),record.changeType(),record.payload());
        }
    }
}
