-- SM-1b schema for PostgreSQL. The application owns immutable user keys.
CREATE TABLE navigation_menu (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version bigint NOT NULL,
    created_at timestamp(6), modified_at timestamp(6),
    created_by varchar(255), modified_by varchar(255),
    name varchar(120) NOT NULL,
    normalized_name varchar(120) NOT NULL,
    main_key integer,
    position integer NOT NULL,
    seeded_at timestamp(6) with time zone NOT NULL,
    change_sequence bigint NOT NULL,
    CONSTRAINT navigation_menu_name_uk UNIQUE (normalized_name),
    CONSTRAINT navigation_menu_main_uk UNIQUE (main_key),
    CONSTRAINT navigation_menu_main_ck CHECK (main_key = 1)
);
CREATE TABLE navigation_section (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version bigint NOT NULL,
    created_at timestamp(6), modified_at timestamp(6),
    created_by varchar(255), modified_by varchar(255),
    menu_id bigint NOT NULL,
    section_key varchar(190) NOT NULL,
    parent_id bigint,
    title varchar(120) NOT NULL,
    icon varchar(64) NOT NULL,
    position integer NOT NULL,
    area_key varchar(190),
    CONSTRAINT navigation_section_key_uk UNIQUE (menu_id, section_key),
    CONSTRAINT navigation_section_area_uk UNIQUE (menu_id, area_key),
    CONSTRAINT navigation_section_menu_fk FOREIGN KEY (menu_id) REFERENCES navigation_menu(id),
    CONSTRAINT navigation_section_parent_fk FOREIGN KEY (parent_id) REFERENCES navigation_section(id)
);
CREATE TABLE navigation_entry (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version bigint NOT NULL,
    created_at timestamp(6), modified_at timestamp(6),
    created_by varchar(255), modified_by varchar(255),
    menu_id bigint NOT NULL,
    entry_key varchar(190) NOT NULL,
    section_id bigint NOT NULL,
    function_key varchar(190) NOT NULL,
    title varchar(120),
    position integer NOT NULL,
    importance varchar(12) NOT NULL DEFAULT 'NORMAL',
    CONSTRAINT navigation_entry_key_uk UNIQUE (menu_id, entry_key),
    CONSTRAINT navigation_entry_importance_ck CHECK (importance IN ('IMPORTANT', 'NORMAL', 'SEE_ALSO')),
    CONSTRAINT navigation_entry_menu_fk FOREIGN KEY (menu_id) REFERENCES navigation_menu(id),
    CONSTRAINT navigation_entry_section_fk FOREIGN KEY (section_id) REFERENCES navigation_section(id)
);
CREATE TABLE navigation_assignment (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version bigint NOT NULL,
    created_at timestamp(6), modified_at timestamp(6),
    created_by varchar(255), modified_by varchar(255),
    user_key varchar(190) NOT NULL,
    menu_id bigint NOT NULL,
    CONSTRAINT navigation_assignment_user_uk UNIQUE (user_key),
    CONSTRAINT navigation_assignment_menu_fk FOREIGN KEY (menu_id) REFERENCES navigation_menu(id)
);
CREATE INDEX navigation_assignment_menu_idx ON navigation_assignment(menu_id);

CREATE TABLE navigation_known_function (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version bigint NOT NULL,
    created_at timestamp(6), modified_at timestamp(6),
    created_by varchar(255), modified_by varchar(255),
    function_key varchar(190) NOT NULL UNIQUE,
    first_seen_at timestamp(6) with time zone NOT NULL
);
