-- KI-2 additive DDL. Apply once to a prepared pilot database before enabling navigation.
-- No app_user FK: user_key is an opaque immutable identity owned by the application.
CREATE TABLE navigation_profile (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version bigint NOT NULL,
    created_at timestamp(6), modified_at timestamp(6),
    created_by varchar(255), modified_by varchar(255),
    name varchar(120) NOT NULL,
    normalized_name varchar(120) NOT NULL,
    change_sequence bigint NOT NULL,
    CONSTRAINT navigation_profile_name_uk UNIQUE (normalized_name)
);
CREATE TABLE navigation_override (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version bigint NOT NULL,
    created_at timestamp(6), modified_at timestamp(6),
    created_by varchar(255), modified_by varchar(255),
    profile_id bigint NOT NULL,
    target_key varchar(190) NOT NULL,
    visibility varchar(8) NOT NULL,
    CONSTRAINT navigation_override_target_uk UNIQUE (profile_id, target_key),
    CONSTRAINT navigation_override_profile_fk FOREIGN KEY (profile_id) REFERENCES navigation_profile(id),
    CONSTRAINT navigation_override_visibility_ck CHECK (visibility IN ('SHOW', 'HIDE'))
);
CREATE TABLE navigation_assignment (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version bigint NOT NULL,
    created_at timestamp(6), modified_at timestamp(6),
    created_by varchar(255), modified_by varchar(255),
    user_key varchar(190) NOT NULL,
    profile_id bigint NOT NULL,
    CONSTRAINT navigation_assignment_user_uk UNIQUE (user_key),
    CONSTRAINT navigation_assignment_profile_fk FOREIGN KEY (profile_id) REFERENCES navigation_profile(id)
);
CREATE INDEX navigation_assignment_profile_idx ON navigation_assignment(profile_id);

-- SM-1 structure storage.
CREATE TABLE navigation_structure (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version bigint NOT NULL,
    created_at timestamp(6), modified_at timestamp(6),
    created_by varchar(255), modified_by varchar(255),
    singleton_key integer NOT NULL UNIQUE CHECK (singleton_key = 1),
    seeded_at timestamp(6) with time zone NOT NULL,
    change_sequence bigint NOT NULL
);
CREATE TABLE navigation_section (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version bigint NOT NULL,
    created_at timestamp(6), modified_at timestamp(6),
    created_by varchar(255), modified_by varchar(255),
    section_key varchar(190) NOT NULL UNIQUE,
    parent_id bigint,
    title varchar(120) NOT NULL,
    icon varchar(64) NOT NULL,
    position integer NOT NULL,
    area_key varchar(190) UNIQUE,
    CONSTRAINT navigation_section_parent_fk FOREIGN KEY (parent_id) REFERENCES navigation_section(id)
);
CREATE TABLE navigation_entry (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version bigint NOT NULL,
    created_at timestamp(6), modified_at timestamp(6),
    created_by varchar(255), modified_by varchar(255),
    entry_key varchar(190) NOT NULL UNIQUE,
    section_id bigint NOT NULL,
    function_key varchar(190) NOT NULL,
    title varchar(120),
    position integer NOT NULL,
    CONSTRAINT navigation_entry_section_fk FOREIGN KEY (section_id) REFERENCES navigation_section(id)
);
CREATE TABLE navigation_known_function (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version bigint NOT NULL,
    created_at timestamp(6), modified_at timestamp(6),
    created_by varchar(255), modified_by varchar(255),
    function_key varchar(190) NOT NULL UNIQUE,
    first_seen_at timestamp(6) with time zone NOT NULL
);
